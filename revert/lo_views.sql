-- Revert libroyal:lo_views from pg
-- Drops the generated views too.

BEGIN;

DROP TRIGGER documents_lo_sync ON public.documents;
DROP TRIGGER projects_lo_sync ON public.projects;
DROP FUNCTION public.lo_sync_trigger();
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT c.relname FROM pg_class c
          JOIN pg_description d ON d.objoid = c.oid AND d.classoid = 'pg_class'::regclass AND d.objsubid = 0
         WHERE c.relkind = 'v' AND c.relnamespace = 'public'::regnamespace
           AND d.description LIKE 'generated by lo_sync()%'
    LOOP
        EXECUTE format('DROP VIEW public.%I', r.relname);
    END LOOP;
END $$;
DROP FUNCTION public.lo_sync();
DROP FUNCTION public.lo_bibliography_rows(text, bigint);

COMMIT;
